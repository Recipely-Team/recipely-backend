#!/usr/bin/env node
/**
 * Food catalogue → data migration.
 *
 * The curated catalogue lives as data in prisma/food-catalog/: `_labels.json`
 * (locales, variant names, category names) and one `NN-<category>.json` per
 * shelf, in shelf order. This script validates it and writes the idempotent
 * upsert migration that puts it in the database, so a deploy (`prisma migrate
 * deploy`) is all it takes, and a later catalogue edit is a new migration
 * generated the same way.
 *
 *   node scripts/generate-food-catalog-migration.mjs <migration_dir_name>   # write
 *   node scripts/generate-food-catalog-migration.mjs --check               # verify the newest one is current
 *
 * Variant tuple: [labelKey, kcal, protein, carbs, fat, fiber, sugar, salt],
 * per 100 g or ml of the food's unit. Servings: [[ServingUnitKey, amount]].
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CATALOG = path.join(ROOT, 'prisma', 'food-catalog');
const MIGRATIONS = path.join(ROOT, 'prisma', 'migrations');
const MARKER = '-- generated by scripts/generate-food-catalog-migration.mjs';
const SERVING_KEYS = new Set(['glass', 'teaGlass', 'can', 'bottle', 'slice', 'piece', 'pack', 'tbsp', 'medium']);
const UNITS = new Set(['g', 'ml']);

export function loadCatalog() {
  const labels = JSON.parse(fs.readFileSync(path.join(CATALOG, '_labels.json'), 'utf8'));
  const shelves = fs
    .readdirSync(CATALOG)
    .filter((f) => /^\d{2}-[a-z-]+\.json$/.test(f))
    .sort()
    .map((f) => ({ file: f, ...JSON.parse(fs.readFileSync(path.join(CATALOG, f), 'utf8')) }));
  return { labels, shelves };
}

const named = (locales, values) => Object.fromEntries(locales.map((locale, i) => [locale, values[i]]));

/** Every problem in the catalogue, as readable lines; empty when it is sound. */
export function validate({ labels, shelves }) {
  const problems = [];
  const { locales } = labels;
  const slugs = new Set();
  for (const shelf of shelves) {
    if (!labels.categories?.[shelf.category]) problems.push(`${shelf.file}: category ${shelf.category} has no names`);
    for (const food of shelf.foods) {
      const at = `${shelf.file} ${food.slug}`;
      if (slugs.has(food.slug)) problems.push(`${at}: duplicate slug`);
      slugs.add(food.slug);
      if (!UNITS.has(food.unit)) problems.push(`${at}: unit ${food.unit}`);
      if (food.names.length !== locales.length || food.names.some((n) => typeof n !== 'string' || n.trim() === '')) {
        problems.push(`${at}: needs ${locales.length} names`);
      }
      for (const [key, amount] of food.servings) {
        if (!SERVING_KEYS.has(key) || !(amount > 0)) problems.push(`${at}: serving ${key} ${amount}`);
      }
      const keys = new Set();
      for (const variant of food.variants) {
        const [key, kcal, protein, carbs, fat, fiber, sugar, salt] = variant;
        if (variant.length !== 8) problems.push(`${at} ${key}: tuple needs 8 values`);
        if (keys.has(key)) problems.push(`${at}: duplicate variant ${key}`);
        keys.add(key);
        if (!labels.labels[key]) problems.push(`${at}: variant ${key} has no label`);
        if ([kcal, protein, carbs, fat, fiber, sugar, salt].some((v) => typeof v !== 'number' || v < 0 || v > 900)) {
          problems.push(`${at} ${key}: values out of range`);
        }
        // Carbohydrate is total (USDA "by difference"), so it already holds fibre and sugar.
        if (protein + carbs + fat + salt > 100.5) problems.push(`${at} ${key}: more than 100 g per 100 g`);
        if (sugar > carbs + 0.01) problems.push(`${at} ${key}: sugar above carbs`);
        if (fiber > carbs + 0.01) problems.push(`${at} ${key}: fibre above carbs`);
        // Energy must follow from the macros (Atwater 4/4/9) unless alcohol supplies it.
        const fromMacros = protein * 4 + carbs * 4 + fat * 9;
        if (!food.alcoholic && Math.abs(fromMacros - kcal) > Math.max(25, kcal * 0.15)) {
          problems.push(`${at} ${key}: ${kcal} kcal but macros give ${fromMacros.toFixed(0)}`);
        }
      }
    }
  }
  for (const [key, names] of Object.entries({ ...labels.labels, ...labels.categories })) {
    if (names.length !== locales.length) problems.push(`label ${key}: needs ${locales.length} names`);
  }
  return problems;
}

const sqlText = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sqlJson = (value) => `${sqlText(JSON.stringify(value))}::jsonb`;
const sqlNum = (value) => String(value);

export function render({ labels, shelves }) {
  const { locales } = labels;
  const lines = [
    MARKER,
    '-- Curated food catalogue: categories, foods and variants, upserted by key so a',
    '-- regenerated catalogue updates rows in place. Rows the catalogue no longer',
    '-- lists are removed (a diary entry keeps its snapshot; its variant link is nulled).',
    '',
  ];
  const categories = shelves.map((s) => s.category);
  categories.forEach((key, rank) => {
    lines.push(
      `INSERT INTO "food_categories" ("key", "names", "rank") VALUES (${sqlText(key)}, ${sqlJson(named(locales, labels.categories[key]))}, ${rank})`,
      `ON CONFLICT ("key") DO UPDATE SET "names" = EXCLUDED."names", "rank" = EXCLUDED."rank";`,
    );
  });
  lines.push('');
  let rank = 0;
  const kept = [];
  for (const shelf of shelves) {
    for (const food of shelf.foods) {
      lines.push(
        `INSERT INTO "foods" ("slug", "category", "names", "default_unit", "rank") VALUES (${sqlText(food.slug)}, ${sqlText(shelf.category)}, ${sqlJson(named(locales, food.names))}, ${sqlText(food.unit)}, ${rank})`,
        `ON CONFLICT ("slug") DO UPDATE SET "category" = EXCLUDED."category", "names" = EXCLUDED."names", "default_unit" = EXCLUDED."default_unit", "rank" = EXCLUDED."rank";`,
      );
      rank += 1;
      const servings = food.servings.map(([key, amount]) => ({ key, amount }));
      food.variants.forEach(([key, kcal, protein, carbs, fat, fiber, sugar, salt], position) => {
        kept.push(`(${sqlText(food.slug)}, ${sqlText(key)})`);
        lines.push(
          `INSERT INTO "food_variants" ("food_id", "key", "names", "position", "kcal", "protein", "carbs", "fat", "fiber", "sugar", "salt", "serving_units", "source")`,
          `SELECT f."id", ${sqlText(key)}, ${sqlJson(named(locales, labels.labels[key]))}, ${position}, ${[kcal, protein, carbs, fat, fiber, sugar, salt].map(sqlNum).join(', ')}, ${sqlJson(servings)}, 'curated' FROM "foods" f WHERE f."slug" = ${sqlText(food.slug)}`,
          `ON CONFLICT ("food_id", "key") DO UPDATE SET "names" = EXCLUDED."names", "position" = EXCLUDED."position", "kcal" = EXCLUDED."kcal", "protein" = EXCLUDED."protein", "carbs" = EXCLUDED."carbs", "fat" = EXCLUDED."fat", "fiber" = EXCLUDED."fiber", "sugar" = EXCLUDED."sugar", "salt" = EXCLUDED."salt", "serving_units" = EXCLUDED."serving_units", "source" = EXCLUDED."source";`,
        );
      });
    }
  }
  lines.push(
    '',
    `DELETE FROM "food_variants" v USING "foods" f WHERE f."id" = v."food_id" AND (f."slug", v."key") NOT IN (${kept.join(', ')});`,
    `DELETE FROM "foods" WHERE "slug" NOT IN (${shelves.flatMap((s) => s.foods.map((f) => sqlText(f.slug))).join(', ')});`,
    `DELETE FROM "food_categories" WHERE "key" NOT IN (${categories.map(sqlText).join(', ')});`,
    '',
  );
  return lines.join('\n');
}

/** The newest migration this script wrote, or undefined. */
function newestGenerated() {
  return fs
    .readdirSync(MIGRATIONS)
    .filter((d) => fs.existsSync(path.join(MIGRATIONS, d, 'migration.sql')))
    .sort()
    .reverse()
    .find((d) => fs.readFileSync(path.join(MIGRATIONS, d, 'migration.sql'), 'utf8').startsWith(MARKER));
}

function main() {
  const catalog = loadCatalog();
  const problems = validate(catalog);
  if (problems.length > 0) {
    console.error(`food catalogue — ${problems.length} problem(s):\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  const sql = render(catalog);
  const arg = process.argv[2];
  if (arg === '--check') {
    const newest = newestGenerated();
    const current = newest && fs.readFileSync(path.join(MIGRATIONS, newest, 'migration.sql'), 'utf8');
    if (current !== sql) {
      console.error('food catalogue changed — generate a new migration: node scripts/generate-food-catalog-migration.mjs <timestamp>_food_catalog_update');
      process.exit(1);
    }
    console.log(`food catalogue — OK (${newest})`);
    return;
  }
  if (!arg || !/^\d{14}_[a-z0-9_]+$/.test(arg)) {
    console.error('usage: generate-food-catalog-migration.mjs <YYYYMMDDHHMMSS_name> | --check');
    process.exit(1);
  }
  fs.mkdirSync(path.join(MIGRATIONS, arg), { recursive: true });
  fs.writeFileSync(path.join(MIGRATIONS, arg, 'migration.sql'), sql);
  console.log(`wrote prisma/migrations/${arg}/migration.sql`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
